// Ответы-заглушки, чтобы разрабатывать интерфейс без бэкенда.
// Формат ответа — как в docs/api-contract.md.

const delay = (ms) => new Promise((r) => setTimeout(r, ms))

export async function mockReply(message) {
  await delay(700)
  const q = message.toLowerCase()

  if (q.includes('опиши данные') || (q.includes('что') && (q.includes('данн') || q.includes('есть')))) {
    return {
      answer:
        'Это данные интернет-магазина: продажи и возвраты товаров за период с октября 2024 года. ' +
        'В таблице 500 000 операций и 22 поля: заказ, покупатель, город, канал продажи, товар, цена, скидка, способ оплаты. ' +
        'Каждая строка — одна товарная позиция заказа.',
      table: {
        columns: ['Показатель', 'Значение'],
        rows: [
          ['Строк', '500 000'],
          ['Полей', '22'],
          ['Начало периода', '2024-10-01'],
          ['Каналов продажи', '3'],
        ],
      },
      sql: 'SELECT count(*) FROM sales;',
    }
  }

  if (q.includes('динамик') || q.includes('месяц') || q.includes('время')) {
    return {
      answer: 'Выручка по месяцам: пик в декабре, после праздников спад, с весны рост.',
      chart: {
        type: 'line',
        title: 'Выручка по месяцам',
        y_label: 'Выручка, руб.',
        categories: ['2024-10-01', '2024-11-01', '2024-12-01', '2025-01-01', '2025-02-01', '2025-03-01',
          '2025-04-01', '2025-05-01', '2025-06-01', '2025-07-01', '2025-08-01', '2025-09-01'],
        series: [{ name: 'Выручка, руб.', data: [41250300, 47120800, 58340100, 39110450, 36250900, 44080200,
          45610700, 47920300, 46180500, 44730900, 48210600, 50380100] }],
      },
      sql: "SELECT date_trunc('month', \"Дата операции (МСК)\") AS \"Месяц\", sum(...) AS \"Выручка, руб.\" FROM t GROUP BY 1 ORDER BY 1;",
    }
  }

  if (q.includes('всего') || q.includes('итог') || q.includes('сколько')) {
    return {
      answer: 'За весь период выручка составила около 549 млн руб. по 498 тыс. заказов, средний чек — 1 102 руб.',
      table: {
        columns: ['Выручка, руб.', 'Заказов', 'Средний чек, руб.'],
        rows: [[549186550.5, 498312, 1102.06]],
      },
      sql: 'SELECT sum(...) AS "Выручка, руб.", count(DISTINCT "Код заказа") AS "Заказов", ... FROM t;',
    }
  }

  if (q.includes('регион') || q.includes('город') || q.includes('канал') || q.includes('продаж')) {
    return {
      answer: 'Больше всего продаж приходится на интернет-магазин, мобильное приложение заметно отстаёт.',
      chart: {
        type: 'bar',
        title: 'Продажи по каналам, тыс. операций',
        categories: ['Интернет-магазин', 'Розничный магазин', 'Мобильное приложение'],
        series: [{ name: 'Операций', data: [214, 176, 110] }],
      },
      sql: 'SELECT channel, count(*) FROM sales GROUP BY channel;',
    }
  }

  return {
    answer: 'Уточните, пожалуйста, что именно вы хотите узнать.',
    clarification: {
      question: 'Вот что я могу показать:',
      options: ['Опиши данные', 'Продажи по каналам', 'Динамика продаж по месяцам', 'Сколько всего выручки?'],
    },
  }
}
